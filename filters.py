"""Conservative shared exclusion and review rules; never infer event location."""
import re
import unicodedata

MUSIC = re.compile(r'\bfleetwood\s*mac\b|\bstevie\s+nicks\b|\bthe\s+(?:dixie\s+)?chicks\b|\blyrics?\b|\b(?:official\s+music\s+video|lyric\s+video|karaoke|remaster(?:ed)?|acoustic\s+cover|guitar\s+cover|piano\s+cover|music\s+video)\b', re.I)
GAME = re.compile(r'\b(?:gameplay|video game|roblox|minecraft|fortnite|game walkthrough)\b', re.I)
POLITICAL = re.compile(r'\blandslide\s+(?:victory|win|election)\b|\b(?:election|electoral)\s+landslide\b', re.I)
COMPILATION = re.compile(r'\b(?:top\s*\d+|compilations?|best of|\d+\s+(?:most\s+)?(?:extreme\s+)?(?:landslides?|earthquakes?|tsunamis?|floods?|hurricanes?|typhoons?)|\d+\s+minutos\s+d[aeos]+|\d+\s+deslizamentos|coletanea|compilacao|compilacion|recopilacion|zusammenschnitt|bestenliste)\b|総集編|まとめ|\d+選|合集|盘点|盤點|모음|총정리|подборка', re.I)
EDUCATIONAL = re.compile(r'\b(?:what is|what are|how do|how does|explained|science experiment|simulation|tutorial|como acontece|o que e|desastres naturais em \d+ minuto)\b|とは何|仕組み|シミュレーション', re.I)

def clean(s):
    return ''.join(c for c in unicodedata.normalize('NFD',str(s or '').casefold()) if not unicodedata.combining(c))

def assess(row, profile):
    """Return reject/review/eligible plus reason. Only obvious exclusions are rejected."""
    title=clean(' '.join(str(row.get(k) or '') for k in ('title','search_title')))
    channel=clean(row.get('channel'))
    category=clean(row.get('category'))
    description=clean(row.get('description'))
    music_meta=bool(re.search(r'provided to youtube by|auto-generated by youtube|\bgenre:\s*(?:rock|pop)|\blyrics\s*:',description))
    # Music category alone is not proof; explicit music evidence is required.
    if MUSIC.search(title) or MUSIC.search(channel) or (category=='music' and music_meta):
        return 'reject','explicit music/artist/title evidence'
    if GAME.search(title):
        return 'reject','explicit gaming title'
    if category=='gaming': return 'review','gaming category without conclusive title evidence'
    if profile['keyword'].casefold()=='landslide' and POLITICAL.search(title):
        return 'reject','political landslide phrase'
    if COMPILATION.search(title): return 'review','compilation or multiple events'
    if EDUCATIONAL.search(title): return 'review','educational or simulated content'
    if category=='music': return 'review','music category without conclusive title evidence'
    return 'eligible','no obvious exclusion'
